// Writes lib/buildInfo.js before a web build (and before a dev server starts)
// so the running app can say which commit it is. The stamp is generated, not
// committed: a checked-in id would be the one thing about it that could lie.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));

function git(args) {
  try {
    return execFileSync('git', args, {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch (e) {
    return '';
  }
}

// A build uploaded from somewhere without git history can still be labelled.
const fromEnv = String(process.env.TRNV_BUILD_ID || '').trim();
const commit = fromEnv || git(['rev-parse', '--short', 'HEAD']) || 'unknown';
const branch = git(['rev-parse', '--abbrev-ref', 'HEAD']) || '';
// Untracked files are ignored: this generated file is one of them, and the
// build itself is not part of what was committed.
const dirty = !fromEnv && git(['status', '--porcelain', '--untracked-files=no']) !== '';

const builtAt = new Date().toISOString().replace(/\.\d{3}Z$/, 'Z');
const info = {
  id: dirty ? `${commit}-dirty` : commit,
  commit,
  branch,
  builtAt,
  dirty,
};

const body = `// Generated by scripts/build-stamp.mjs. Do not edit and do not commit.
export const BUILD = ${JSON.stringify(info, null, 2)};
`;

writeFileSync(join(root, 'lib', 'buildInfo.js'), body);
console.log(`build stamp: ${info.id} · ${info.builtAt}`);
